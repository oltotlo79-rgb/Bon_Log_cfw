━━━━━━━━━━━━━━━━━━━━━━━

ジン（枯れ枝）・舎利（枯れた幹・樹皮が剥けた部位）は盆栽の美的表現として重要な要素ですが、病原菌・害虫の巣になるリスクがあります。

【定期的なメンテナンス】

・ライム・サルファー（石灰硫黄合剤）の塗り込み
 石灰硫黄合剤を刷毛でジン・舎利部分に塗り込むことで、腐朽菌・害虫の侵入を防ぎ、白く漂白された美しい外観を維持できる。年1〜2回（冬季）が目安。

・木部保護剤の塗布
 ジン・舎利の末端（先端）から水が侵入すると腐朽が進む。末端部にトップジンMペーストまたは木部保護専用剤を塗布して封じる。

・腐朽の点検
 毎年冬季に舎利部分をナイフでつつき、木部が軟化（腐朽の始まり）していないか確認する。


